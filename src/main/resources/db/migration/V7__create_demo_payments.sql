CREATE TABLE demo_wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    balance_kzt BIGINT NOT NULL DEFAULT 0 CHECK (balance_kzt >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    wallet_id BIGINT NOT NULL REFERENCES demo_wallets(id),
    amount_kzt BIGINT NOT NULL CHECK (amount_kzt >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('APPROVED', 'DECLINED', 'REFUNDED')),
    failure_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idempotency_key UUID UNIQUE
);
CREATE UNIQUE INDEX idx_payments_one_success_per_order ON payments(order_id) WHERE status IN ('APPROVED', 'REFUNDED');
CREATE INDEX idx_payments_order ON payments(order_id);
CREATE INDEX idx_payments_wallet ON payments(wallet_id);

CREATE TABLE wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL REFERENCES demo_wallets(id),
    payment_id BIGINT REFERENCES payments(id),
    operation VARCHAR(20) NOT NULL CHECK (operation IN ('CREDIT', 'DEBIT', 'REFUND')),
    amount_kzt BIGINT NOT NULL CHECK (amount_kzt > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((operation = 'CREDIT' AND payment_id IS NULL) OR (operation IN ('DEBIT', 'REFUND') AND payment_id IS NOT NULL))
);
CREATE UNIQUE INDEX idx_wallet_transactions_payment_operation ON wallet_transactions(payment_id, operation) WHERE payment_id IS NOT NULL;
CREATE INDEX idx_wallet_transactions_wallet ON wallet_transactions(wallet_id, created_at DESC);
