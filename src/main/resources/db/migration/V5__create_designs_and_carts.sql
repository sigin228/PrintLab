CREATE TABLE designs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(150) NOT NULL,
    print_text TEXT,
    image_path TEXT,
    placement VARCHAR(20) NOT NULL DEFAULT 'BOTH',
    print_price_kzt BIGINT NOT NULL DEFAULT 0 CHECK (print_price_kzt >= 0),
    editor_state JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(editor_state) = 'object'),
    preview_front_path TEXT,
    preview_back_path TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editor_version INTEGER NOT NULL DEFAULT 1 CHECK (editor_version > 0)
);
CREATE INDEX idx_designs_user ON designs(user_id);

CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
    variant_id BIGINT NOT NULL REFERENCES product_variants(id),
    design_id BIGINT REFERENCES designs(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_cart_items_cart ON cart_items(cart_id);
CREATE INDEX idx_cart_items_variant ON cart_items(variant_id);
CREATE INDEX idx_cart_items_design ON cart_items(design_id);
