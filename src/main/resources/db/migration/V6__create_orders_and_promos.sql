CREATE TABLE promo_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE CHECK (length(trim(code)) > 0 AND code = upper(code)),
    discount_type VARCHAR(20) NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value BIGINT NOT NULL CHECK (discount_value > 0),
    min_order_kzt BIGINT NOT NULL DEFAULT 0 CHECK (min_order_kzt >= 0),
    usage_limit INTEGER CHECK (usage_limit > 0),
    starts_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (discount_type <> 'PERCENT' OR discount_value <= 100),
    CHECK (starts_at IS NULL OR expires_at IS NULL OR starts_at < expires_at)
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    promo_code_id BIGINT REFERENCES promo_codes(id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('AWAITING_PAYMENT', 'PAID_SIMULATED', 'IN_PRODUCTION', 'READY', 'COMPLETED', 'CANCELLED')),
    subtotal_kzt BIGINT NOT NULL CHECK (subtotal_kzt >= 0),
    discount_kzt BIGINT NOT NULL CHECK (discount_kzt >= 0 AND discount_kzt <= subtotal_kzt),
    total_kzt BIGINT NOT NULL CHECK (total_kzt >= 0 AND total_kzt = subtotal_kzt - discount_kzt),
    delivery_name VARCHAR(150) NOT NULL CHECK (length(trim(delivery_name)) > 0),
    delivery_phone VARCHAR(40) NOT NULL CHECK (length(trim(delivery_phone)) > 0),
    delivery_address TEXT NOT NULL CHECK (length(trim(delivery_address)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    checkout_key UUID UNIQUE,
    stock_reserved BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_orders_user ON orders(user_id, created_at DESC);
CREATE INDEX idx_orders_promo ON orders(promo_code_id);
CREATE INDEX idx_orders_status ON orders(status);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    variant_id BIGINT NOT NULL REFERENCES product_variants(id),
    design_id BIGINT REFERENCES designs(id) ON DELETE SET NULL,
    product_name_snapshot VARCHAR(150) NOT NULL,
    size_snapshot VARCHAR(10) NOT NULL,
    color_snapshot VARCHAR(40) NOT NULL,
    image_url_snapshot TEXT,
    design_snapshot JSONB CHECK (design_snapshot IS NULL OR jsonb_typeof(design_snapshot) = 'object'),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_kzt BIGINT NOT NULL CHECK (unit_price_kzt >= 0),
    line_total_kzt BIGINT NOT NULL CHECK (line_total_kzt >= 0 AND line_total_kzt::numeric = unit_price_kzt::numeric * quantity)
);
CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_order_items_variant ON order_items(variant_id);
CREATE INDEX idx_order_items_design ON order_items(design_id);
